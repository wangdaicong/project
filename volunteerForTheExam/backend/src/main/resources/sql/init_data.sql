-- 5. 添加院校专业关联数据（每个院校开设的专业）
INSERT INTO university_major (university_id, major_id, enrollment_plan, tuition_fee, created_time, updated_time)
SELECT 
    u.id as university_id,
    m.id as major_id,
    CASE 
        WHEN u.is_985 = 1 THEN 80 + FLOOR(RAND() * 40)
        WHEN u.is_211 = 1 THEN 100 + FLOOR(RAND() * 50)
        ELSE 120 + FLOOR(RAND() * 80)
    END as enrollment_plan,
    CASE 
        WHEN m.category = '艺术学' THEN 10000 + FLOOR(RAND() * 5000)
        WHEN m.category IN ('医学', '工学') THEN 6000 + FLOOR(RAND() * 3000)
        ELSE 5000 + FLOOR(RAND() * 2000)
    END as tuition_fee,
    NOW() as created_time,
    NOW() as updated_time
FROM 
    university u
CROSS JOIN 
    major_info m
WHERE 
    -- 综合类大学开设所有专业
    (u.type = '综合' AND m.id <= 40)
    -- 理工类大学主要开设工学、理学专业
    OR (u.type = '理工' AND m.category IN ('工学', '理学', '经济学', '管理学'))
    -- 师范类大学主要开设教育学、文学专业
    OR (u.type = '师范' AND m.category IN ('教育学', '文学', '理学', '历史学'))
    -- 农林类大学主要开设农学专业
    OR (u.type = '农林' AND m.category IN ('农学', '理学', '工学'))
ON DUPLICATE KEY UPDATE updated_time = NOW();

