-- 3. 增加历年录取数据（2024-2026年）
-- 注意：这里使用示例数据，实际应用中需要从真实数据源获取
INSERT INTO score_line (university_id, province, year, category, batch, min_score, avg_score, max_score, min_rank, created_time, updated_time)
SELECT 
    u.id as university_id,
    p.province,
    y.year,
    c.category,
    '本科一批' as batch,
    CASE 
        WHEN u.is_985 = 1 THEN 620 + FLOOR(RAND() * 30)
        WHEN u.is_211 = 1 THEN 590 + FLOOR(RAND() * 30)
        ELSE 550 + FLOOR(RAND() * 40)
    END as min_score,
    CASE 
        WHEN u.is_985 = 1 THEN 635 + FLOOR(RAND() * 25)
        WHEN u.is_211 = 1 THEN 605 + FLOOR(RAND() * 25)
        ELSE 570 + FLOOR(RAND() * 30)
    END as avg_score,
    CASE 
        WHEN u.is_985 = 1 THEN 660 + FLOOR(RAND() * 20)
        WHEN u.is_211 = 1 THEN 630 + FLOOR(RAND() * 20)
        ELSE 600 + FLOOR(RAND() * 30)
    END as max_score,
    CASE 
        WHEN u.is_985 = 1 THEN 1000 + FLOOR(RAND() * 2000)
        WHEN u.is_211 = 1 THEN 3000 + FLOOR(RAND() * 5000)
        ELSE 10000 + FLOOR(RAND() * 20000)
    END as min_rank,
    NOW() as created_time,
    NOW() as updated_time
FROM 
    university u
CROSS JOIN 
    (SELECT '北京' as province UNION SELECT '上海' UNION SELECT '广东' UNION SELECT '浙江' 
     UNION SELECT '江苏' UNION SELECT '山东' UNION SELECT '湖北' UNION SELECT '四川') p
CROSS JOIN
    (SELECT 2024 as year UNION SELECT 2025 UNION SELECT 2026) y
CROSS JOIN
    (SELECT '理科' as category UNION SELECT '文科') c
WHERE u.id <= 35
ON DUPLICATE KEY UPDATE updated_time = NOW();

