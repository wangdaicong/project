CREATE TABLE score_line (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    university_id BIGINT NOT NULL COMMENT '院校ID',
    university_name VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '院校名称',
    province VARCHAR(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '省份',
    year INT NOT NULL COMMENT '年份',
    batch VARCHAR(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci COMMENT '批次',
    category VARCHAR(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci COMMENT '科类',
    min_score INT COMMENT '最低分',
    avg_score INT COMMENT '平均分',
    max_score INT COMMENT '最高分',
    min_rank INT COMMENT '最低位次',
    enrollment_count INT COMMENT '招生人数',
    created_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_university_id (university_id),
    INDEX idx_province (province),
    INDEX idx_year (year),
    INDEX idx_university_year (university_id, year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='历年分数线表';

